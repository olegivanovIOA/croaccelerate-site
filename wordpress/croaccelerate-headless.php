<?php
/**
 * Plugin Name: CRO Accelerate — Static Site Bridge
 * Description: Lets the static croaccelerate.com site and WordPress live on the same GoDaddy hosting and domain.
 *              Static files/folders (uploaded by GitHub Actions) are served directly by the web server; requests
 *              that reach WordPress are handled here: static home page, old-URL redirects, posts → /blog/<slug>/,
 *              static 404, and a GitHub rebuild trigger when a post is published or updated.
 * Version: 2.0
 * Author: CRO Accelerate
 *
 * INSTALL: the GitHub deploy workflow uploads this file to wp-content/mu-plugins/ automatically.
 *          To remove it: GitHub → Settings → Variables → CRA_PLUGIN = off, then re-run Deploy.
 * CONFIG (wp-config.php, above "That's all, stop editing!"):
 *   (optional) define('CRA_STATIC_HOME', false);           // show the old WordPress home page instead of the new one
 *   define('CRA_GH_REPO',  'olegivanovIOA/croaccelerate-site');
 *   define('CRA_GH_TOKEN', 'github_pat_...');              // fine-grained token: this repo only, Contents: Read & write
 * Remove CRA_STATIC_HOME (or set false) to instantly show the old WordPress home page again — the safety switch.
 */
if (!defined('ABSPATH')) exit;

function cra_static_file($name) {
    $f = ABSPATH . ltrim($name, '/');
    return is_readable($f) ? $f : null;
}

function cra_serve_static($name, $status = 200) {
    $f = cra_static_file($name);
    if (!$f) return false;
    status_header($status);
    header('Content-Type: text/html; charset=utf-8');
    header('Cache-Control: public, max-age=300');
    readfile($f);
    exit;
}

/* 1. Front-end routing for everything that falls through to WordPress. */
add_action('template_redirect', function () {
    if (is_admin() || is_preview() || wp_doing_ajax() || (defined('REST_REQUEST') && REST_REQUEST)) return;
    if (isset($_GET['cra_wp'])) return; // escape hatch: ?cra_wp=1 shows the WordPress page itself
    if (!cra_static_file('blog/index.html')) return; // static site not uploaded yet -> change nothing

    $path = '/' . trim(parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH), '/') . '/';
    if ($path === '//') $path = '/';

    // static home page
    if ($path === '/' && (!defined('CRA_STATIC_HOME') || CRA_STATIC_HOME)) {
        if (cra_serve_static('index.html')) return;
    }

    // explicit redirects generated by the build (old pages -> new structure)
    $map = array();
    if ($f = cra_static_file('redirects.json')) {
        $map = json_decode(file_get_contents($f), true) ?: array();
    }
    if (isset($map[$path])) { wp_redirect($map[$path], 301); exit; }
    if (strpos($path, '/industries/') === 0) { wp_redirect('/cases/', 301); exit; }

    // old post permalinks -> static blog
    if (is_singular('post')) {
        wp_redirect('/blog/' . get_post_field('post_name', get_queried_object_id()) . '/', 301); exit;
    }
    if (is_category()) { wp_redirect('/blog/category/' . get_queried_object()->slug . '/', 301); exit; }
    if (is_feed()) { wp_redirect('/blog/feed.xml', 301); exit; }
    if (is_home() || is_archive() || is_search() || is_author()) { wp_redirect('/blog/', 301); exit; }

    // anything else WordPress cannot match -> static 404 page
    if (is_404()) { cra_serve_static('404.html', 404); }

    // remaining WordPress-rendered pages stay out of search results (the static site is canonical)
    header('X-Robots-Tag: noindex, follow', true);
}, 1);

/* 2. Keep WordPress-generated sitemaps/robots out of the way: the static site ships its own. */
add_filter('wpseo_enable_xml_sitemap', '__return_false');
add_filter('wp_sitemaps_enabled', '__return_false');

/* 3. Rebuild + redeploy the static site when posts change (GitHub repository_dispatch, debounced 60 s). */
function cra_trigger_rebuild($reason) {
    if (!defined('CRA_GH_REPO') || !defined('CRA_GH_TOKEN') || !CRA_GH_TOKEN) return;
    if (get_transient('cra_rebuild_lock')) return;
    set_transient('cra_rebuild_lock', 1, 60);
    wp_remote_post('https://api.github.com/repos/' . CRA_GH_REPO . '/dispatches', array(
        'timeout'  => 8,
        'blocking' => false,
        'headers'  => array(
            'Authorization' => 'Bearer ' . CRA_GH_TOKEN,
            'Accept'        => 'application/vnd.github+json',
            'User-Agent'    => 'cra-wordpress',
        ),
        'body' => wp_json_encode(array('event_type' => 'wp-publish', 'client_payload' => array('reason' => $reason))),
    ));
}
add_action('transition_post_status', function ($new, $old, $post) {
    if ($post->post_type === 'post' && ($new === 'publish' || $old === 'publish')) cra_trigger_rebuild("post {$post->ID}: {$old} -> {$new}");
}, 10, 3);
add_action('post_updated', function ($id, $after) {
    if ($after->post_type === 'post' && $after->post_status === 'publish') cra_trigger_rebuild("post {$id} updated");
}, 10, 2);

/* 4. "View post" in admin opens the public static URL. */
add_filter('post_link', function ($url, $post) {
    if (is_admin() && $post->post_status === 'publish') return home_url('/blog/' . $post->post_name . '/');
    return $url;
}, 10, 2);

/* 5. Let the CRO agent set Yoast title/description on drafts via REST (users with edit rights only). */
add_action('init', function () {
    foreach (array('_yoast_wpseo_title', '_yoast_wpseo_metadesc') as $key) {
        register_post_meta('post', $key, array(
            'show_in_rest' => true, 'single' => true, 'type' => 'string',
            'auth_callback' => function () { return current_user_can('edit_posts'); },
        ));
    }
});
